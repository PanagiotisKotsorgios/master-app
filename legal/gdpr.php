<h2><i class="fas fa-bullhorn" style="color:var(--red);margin-right:.5rem"></i>7. Μαζική Αποστολή Μηνυμάτων (Broadcast)</h2>
<p>Η πλατφόρμα παρέχει δυνατότητα μαζικής αποστολής SMS/Email. Διακρίνονται:</p>
<ul>
  <li><strong>Λειτουργικά μηνύματα</strong> (υπενθυμίσεις ανανέωσης, πληροφορίες σωματείου): Βάση σύμβασης, άρθρο 6§1β ΓΚΠΔ. Δεν απαιτείται ξεχωριστό opt-in.</li>
  <li><strong>Προωθητικά / marketing μηνύματα</strong>: Απαιτείται <strong>ρητό opt-in</strong> σύμφωνα με τον Ν.3471/2006 άρθρο 11 και άρθρο 6§1α ΓΚΠΔ. Ο παραλήπτης πρέπει να έχει δώσει ρητή συγκατάθεση πριν την αποστολή.</li>
</ul>
<div class="info-box gold">
  <p><strong>Υποχρέωση συμμόρφωσης:</strong> Ο διαχειριστής σωματείου ευθύνεται να χρησιμοποιεί τη λειτουργία broadcast αποκλειστικά για νόμιμες κατηγορίες μηνυμάτων. Η αποστολή ανεπιθύμητων εμπορικών μηνυμάτων χωρίς opt-in συνιστά παραβίαση του Ν.3471/2006 και μπορεί να επισύρει κυρώσεις από την ΑΠΔΠΧ.</p>
</div>

