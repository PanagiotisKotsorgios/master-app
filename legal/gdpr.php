<ul>
  <li><strong>Ελεύθερη:</strong> Χωρίς πίεση ή δέσμευση από συμμετοχή στο σωματείο</li>
  <li><strong>Συγκεκριμένη:</strong> Ξεχωριστή για κάθε κατηγορία δεδομένων (γενικά στοιχεία, ζώνες, συνδρομές)</li>
