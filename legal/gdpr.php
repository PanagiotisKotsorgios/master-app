<h2><i class="fas fa-magnifying-glass" style="color:var(--red);margin-right:.5rem"></i>6. Εκτίμηση Αντικτύπου (DPIA — άρθρο 35 ΓΚΠΔ)</h2>
<p>Η επεξεργασία δεδομένων ανήλικων αθλητών ενδέχεται να απαιτεί <strong>DPIA</strong> σύμφωνα με τον κατάλογο υποχρεωτικής DPIA της ΑΠΔΠΧ (άρθρο 35§4 ΓΚΠΔ). Οι ακόλουθοι τύποι επεξεργασίας αποτελούν πιθανά <strong>triggers DPIA</strong> βάσει του καταλόγου ΑΠΔΠΧ:</p>
<ul>
  <li>Επεξεργασία δεδομένων ανήλικων σε μεγάλη κλίμακα</li>
  <li>Παρακολούθηση/monitoring αθλητικής απόδοσης και συμπεριφοράς</li>
</ul>

<div class="info-box gold">
  <p><strong>Template DPIA Summary (για σωματεία-Υπευθύνους):</strong> Η ΚΟΤΣΟΡΓΙΟΣ ΠΑΝΑΓΙΩΤΗΣ παρέχει έτοιμο υπόδειγμα DPIA στους πελάτες, το οποίο καλύπτει όλα τα υποχρεωτικά πεδία (άρθρο 35§7 ΓΚΠΔ):</p>
  <ul style="margin-top:.5rem">
    <li>Περιγραφή επεξεργασίας (σκοποί, συστήματα, ρόλοι)</li>
    <li>Κατηγορίες δεδομένων — ιδίως ανήλικοι</li>
    <li>Νομικές βάσεις ανά σκοπό επεξεργασίας</li>
    <li>Αναγκαιότητα & αναλογικότητα (data minimization, purpose limitation)</li>
    <li>Αξιολόγηση κινδύνων (πιθανότητα × αντίκτυπος)</li>
    <li>Μέτρα μετριασμού — τεχνικά & οργανωτικά</li>
    <li>Υπολειπόμενος κίνδυνος & απόφαση (go / no-go)</li>
    <li>Σχέδιο παρακολούθησης (review cycle)</li>
    <li>Προηγούμενη διαβούλευση με ΑΠΔΠΧ αν ο υπολειπόμενος κίνδυνος παραμένει υψηλός (άρθρο 36)</li>
  </ul>
</div>

