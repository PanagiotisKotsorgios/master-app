<h3>5.1 Εργαλεία που παρέχουμε στο σωματείο (ως Εκτελών)</h3>
<p>Ως Υπεύθυνος Επεξεργασίας για δεδομένα αθλητών/μελών, <strong>εσείς</strong> (σωματείο) είστε υπεύθυνοι να ικανοποιείτε τα αιτήματα. Εμείς σας παρέχουμε τεχνικά εργαλεία μέσω dashboard:</p>
<ul>
  <li><strong>Πρόσβαση & Φορητότητα:</strong> Εξαγωγή δεδομένων αθλητή σε JSON/CSV</li>
  <li><strong>Διόρθωση:</strong> Επεξεργασία στοιχείων από το dashboard</li>
  <li><strong>Διαγραφή:</strong> Οριστική διαγραφή αθλητή και όλων των δεδομένων του (συμπεριλαμβανομένων backups εντός rolling window)</li>
  <li><strong>Περιορισμός:</strong> Επισήμανση «ανενεργός» χωρίς οριστική διαγραφή</li>
  <li><strong>Εναντίωση:</strong> Διακοπή συγκεκριμένων ειδών επεξεργασίας</li>
</ul>

<h3>5.2 Διαδικασία DSAR ως Εκτελών — SOP (Standard Operating Procedure)</h3>
<div class="dpa-clause">
  <strong>Βήμα 1 — Λήψη αιτήματος:</strong> Αν αίτημα άσκησης δικαιώματος (DSAR) υποβληθεί απευθείας στην ΚΟΤΣΟΡΓΙΟΣ ΠΑΝΑΓΙΩΤΗΣ αντί για το σωματείο, το <strong>προωθούμε (forward) αμέσως στον αρμόδιο Υπεύθυνο</strong> (σωματείο) και ενημερώνουμε τον αιτούντα για ποιον πρέπει να απευθύνεται.<br><br>
  <strong>Βήμα 2 — Επαλήθευση ταυτότητας:</strong> Πριν διαθέσουμε δεδομένα ή εκτελέσουμε διαγραφή, απαιτούμε εύλογη επαλήθευση ταυτότητας του αιτούντος (π.χ. επιβεβαίωση μέσω email λογαριασμού ή παροχή στοιχείου που μόνο ο δικαιούχος γνωρίζει). Τούτο αποτρέπει μη εξουσιοδοτημένη πρόσβαση σε δεδομένα τρίτων.<br><br>
  <strong>Βήμα 3 — Εσωτερικό SLA:</strong> Μετά από επαληθευμένο αίτημα από τον Υπεύθυνο (σωματείο), παρέχουμε τεχνική υποστήριξη/εξαγωγή δεδομένων <strong>εντός 5 εργάσιμων ημερών</strong>, ώστε ο Υπεύθυνος να μπορεί να ανταποκριθεί στη νόμιμη προθεσμία των 30 ημερών (άρθρο 12§3 ΓΚΠΔ).<br><br>
  <strong>Βήμα 4 — Backups & audit logs:</strong> Σε αίτημα διαγραφής, τα δεδομένα διαγράφονται από τη λειτουργική βάση άμεσα. Τα rolling backups (30 ημέρες) επικαλύπτονται φυσικά. Τα audit logs δεν περιλαμβάνουν περιεχόμενο που ζητήθηκε να διαγραφεί, μόνο μεταδεδομένα ενεργειών (για λόγους ασφάλειας/νόμιμου συμφέροντος, διατήρηση 6 μηνών).
</div>

