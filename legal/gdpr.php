<p>Η πλατφόρμα επεξεργάζεται δεδομένα ανήλικων αθλητών σύμφωνα με τα άρθρα 8 ΓΚΠΔ και <strong>21 Ν.4624/2019</strong>. Το άρθρο 21 εφαρμόζεται όταν προσφέρονται υπηρεσίες κοινωνίας της πληροφορίας <em>απευθείας σε ανήλικο</em> και η βάση είναι συγκατάθεση — ορίζει όριο <strong>15 ετών</strong>. Ανεξαρτήτως αυτού, τα παιδιά θεωρούνται ευάλωτα υποκείμενα που απαιτούν αυξημένη προστασία.</p>
